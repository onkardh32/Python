# ----------------------------------------
# Logical Operators 
# Used to combine multiple conditions
# ----------------------------------------  
is_raining = True
is_cold = False

print("is_raining and is_cold:", is_raining and is_cold)  # False
print("is_raining or is_cold:", is_raining or is_cold)  # True
print("not is_raining:", not is_raining)  # False       


