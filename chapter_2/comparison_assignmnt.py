# ----------------------------------------
# Comparison Operators
# Used to compare two values (returns True/False)
# ----------------------------------------

a = 10
b = 5

# Equal to (==)
print("a == b:", a == b)

# Not equal (!=)
print("a != b:", a != b)

# Greater than (>)
print("a > b:", a > b)

# Less than (<)
print("a < b:", a < b)

# Greater than or equal to (>=)
print("a >= b:", a >= b)

# Less than or equal to (<=)
print("a <= b:", a <= b)


# ----------------------------------------
# Assignment Operators
# Used to assign and update values in variables
# ----------------------------------------

# Basic Assignment (=)
x = 10
print("x =", x)

# Add and Assign (+=) → x = x + value
x = 10
x += 5
print("x += 5 ->", x)

# Subtract and Assign (-=)
x = 10
x -= 3
print("x -= 3 ->", x)

# Multiply and Assign (*=)
x = 10
x *= 2
print("x *= 2 ->", x)

# Divide and Assign (/=) → result is float
x = 10
x /= 2
print("x /= 2 ->", x)

# Floor Divide and Assign (//=)
x = 10
x //= 3
print("x //= 3 ->", x)

# Modulus and Assign (%=)
x = 10
x %= 3
print("x %= 3 ->", x)

# Exponent and Assign (**=)
x = 2
x **= 3
print("x **= 3 ->", x)


